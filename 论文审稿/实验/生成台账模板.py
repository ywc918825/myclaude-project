# -*- coding: utf-8 -*-
"""生成《成果台账填写模板》——实验一的唯一数据来源，与系统无关。"""
import csv, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xlsx简易写入器 import Workbook

HEAD = ['成果名称', '作者（按署名顺序，用、分隔）', '通讯作者', '标准积分',
        '成果类型（选填）', '完成年份（选填）']
EG = [
    ['南通市某年度手足口病流行特征分析', '张三、李四、王五', '王五', 20, '论文', 2024],
    ['某市饮用水卫生监测能力建设研究', '李四、赵六', '李四', 35, '课题', 2023],
    ['一种病原微生物快速检测方法', '王五、张三、孙七、周八', '', 12, '专利', 2022],
]
NOTE = [
    ['《成果台账》填写说明'],
    [''],
    ['这张表用于实验一（四种分配方法的排名对比），是回应"只有理论对比、没有实验"'],
    ['这条审稿意见的正面答案。它与系统有没有上线、库里有没有数据完全无关——'],
    ['数据来自中心已有的科研成果档案。'],
    [''],
    ['一、必填三列'],
    ['  成果名称    同一件成果只写一行，把所有作者写在同一行里'],
    ['  作者        按署名顺序从左到右，用顿号分隔；分号、逗号、斜杠也可识别'],
    ['  标准积分    该成果按本中心积分办法应得的分值（式(1) 里的 S_total）'],
    ['              注意不是某个人拿到的分，是这件成果本身的分值'],
    [''],
    ['二、通讯作者列'],
    ['  填姓名；没有通讯作者就留空；多个通讯作者用同样的分隔符'],
    ['  按论文规则，通讯作者按第 1 作者系数计'],
    [''],
    ['三、样本量'],
    ['  成果 ≥100 件、涉及人员 ≥30 人，Spearman 秩相关才稳。'],
    ['  三到五年的台账通常就够——论文表4 写着上线前 3 个月线下申报 192 件，'],
    ['  按年折算七百余件。'],
    ['  真正决定实验成败的是"3 人及以上合著成果"的数量：四种分配方法的差异'],
    ['  全部来自这部分，单人成果对结果没有任何贡献。'],
    [''],
    ['四、几个容易出错的地方'],
    ['  · 重名的人请在台账里就区分开，如"张三（检验科）"，脚本按姓名字符串归并'],
    ['  · 通讯作者的姓名必须出现在作者列里，否则脚本会报出这一行让你核对'],
    ['  · 作者顺序不能错，这是整个实验的自变量'],
    ['  · 第 2—4 行是示例，填写前请整行删除'],
    [''],
    ['五、填完之后'],
    ['  另存为 CSV（UTF-8），然后：'],
    ['    python3 台账转实验数据.py 台账.csv --out works.csv --run'],
    ['  脚本会转格式、跑实验，并报告作者数分布、合著比例与有问题的行。'],
]

wb = Workbook()
wb.sheet('成果台账', [HEAD] + EG, widths=[38, 30, 12, 10, 14, 12],
         header=True, freeze=True, dim_from=2)
wb.sheet('填写说明', NOTE, widths=[76], wrap=True)
wb.save('成果台账填写模板.xlsx')
print('已生成 成果台账填写模板.xlsx')

with open('成果台账填写模板.csv', 'w', newline='', encoding='utf-8-sig') as f:
    w = csv.writer(f)
    w.writerow(HEAD)
    w.writerows(EG)
print('已生成 成果台账填写模板.csv（UTF-8 BOM，Excel 可直接打开）')
