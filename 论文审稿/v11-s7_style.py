# -*- coding: utf-8 -*-
"""第七步：公式逻辑补漏 + 去掉三处“三段排比”式的模板腔。"""
import xml.etree.ElementTree as ET
from lib import W, register, rewrite, find, save

SRC = 'work/word/document.xml'
register(SRC)
tree = ET.parse(SRC)
body = tree.getroot().find(W + 'body')
T = 's̃'
log = []

# ── 公式逻辑：τnow 的口径 + W(0) 初值 + 说明两级衰减不重叠 ──────────────
rewrite(find(body, '式中: ' + T),
        '式中: {i|' + T + '}{sub|i,u} 为行为 {i|i} 经时间衰减与归一化后的积分; '
        '{i|W}{sup|(k)}{sub|t,u} 为用户 {i|u} 在标签 {i|t} 上第 {i|k} 个周期(本文指自然年度)'
        '的权重, 初值 {i|W}{sup|(0)}{sub|t,u} 取 0; {i|s}{sub|i,u} 为其在行为 {i|i} 上的'
        '原始积分; {i|m} 为标签 {i|t} 下的行为总数; {i|S}{sub|max,t} 为本周期全中心在标签 '
        '{i|t} 下的最高行为积分, 用于将行为项归一化至 [0, 1]; {i|w}{sub|i} 为行为 {i|i} 的'
        '贡献系数, 满足 Σ{i|w}{sub|i} = 1; {i|τ}{sub|now} 为本周期期末时刻, {i|τ}{sub|i} '
        '为成果完成时间. 需要指出的是, 式(4) 的衰减因子只处理周期内部的时效差异, '
        '跨周期的时效由式(5) 的指数加权承担, 两级衰减各司其职, 不重复计算同一段时间.')
log.append('【公式逻辑】τnow 由“当前时间”改为“本周期期末时刻”, 并补一句说明式(4) 与式(5) '
           '的衰减分工——原来两处都按“当前时间”算, 同一段时间会被指数衰减和 EWMA 各罚一次, '
           '3 年前的成果实际只剩 0.657×0.063≈4%, 远低于任一机制单独作用的结果, '
           '这是审稿人容易追问的点')
log.append('【公式逻辑】补上式(5) 的初值 W(0)t,u = 0——原来递推式没有给起点')

# ── 去 AI 腔 1：摘要开头不再与引言首句雷同 ──────────────────────────
p = find(body, '摘　要')
s = ''.join(t.text or '' for t in p.iter(W + 't'))
s = s.replace('针对疾控机构科研人才评价方式粗放、缺少动态量化手段、难以支撑科研梯队建设与'
              '精准激励的问题, 设计并实现了',
              '基层疾控机构的科研人才评价长期依赖人工台账与年终汇总, 难以刻画个体能力的动态'
              '演进. 为此设计并实现了')
rewrite(p, '{b|摘　要}: ' + s.split(': ', 1)[1]
        .replace('(α = 0.7)', '({i|α} = 0.7)').replace('(λ = 0.14)', '({i|λ} = 0.14)'))
log.append('【文风】摘要首句原与引言首句几乎逐字重复（“方式粗放、缺少动态量化手段、'
           '难以支撑科研梯队建设与精准激励”），改写为从现状切入, 不再复读引言')

# ── 去 AI 腔 2：引言末段由“三点贡献排比”改为论证式 ─────────────────
rewrite(find(body, '李涛等[1]从指标体系角度'),
        '李涛等[1]从指标体系角度探讨了科研评价, 黄钊等[2]与李少琼等[3]分别面向疾控数字化'
        '系统与疾控信息化评价指标展开研究, 但均聚焦机构层面而非个人; 杨思洛等[4]梳理了'
        '“破五唯”导向下科研成果评价的制度表征, Amaral 等[5]、沈杨阳[6]与 Lei[7]分别从'
        '绩效拨款、组织机制与分类绩效角度探讨了科研评价, 但评价对象同样以机构为主; '
        '罗仕鉴等[8]与白菁昊等[9]验证了用户画像与时序动态标签方法的有效性, 胡晓莹等[10]与 '
        'Chen 等[11]将指数加权移动平均与时间衰减引入用户兴趣建模, 但均未考虑科研成果的'
        '长周期性与时效衰减. 两条线索至今没有接上: 评价指标的研究停在机构层面, 动态标签的'
        '研究面向的是消费与学习行为. 本文的做法是把成果积分直接当作行为信号接入标签权重的'
        '更新, 再由标签权重映射到能力维度, 让量化与画像共用一条计算通路. 沿着这条通路, '
        '多作者成果的积分如何分配、标签权重如何随时间衰减、审批环节如何免发布调整, '
        '是必须先解决的三个具体问题.')
log.append('【文风】引言末段原来是“提出…, 构建…, 并实现…”的三点贡献排比, 与摘要、结论'
           '第三次重复同一组句式. 改为先点出两条研究线索的断裂, 再说本文的接法, '
           '最后引出三个待解问题——同时也把后文 3.2/3.3/3.5 三节的顺序交代清楚了')

# ── 去 AI 腔 3：结论不再复述三点贡献, 改为结果 + 判断 + 局限 ───────────
rewrite(find(body, '本文设计并实现了基于'),
        '系统在南通市疾控中心运行 3 个月, 平均审核周期由 7 d 降至 2 d, 积分核算差错率由 '
        '3.54% 降至 0.08%, 动态能力标签与专家标注的 {i|F}1 值为 0.86. 把时间衰减放在行为'
        '积分层而不是能力得分层, 是让标签权重、能力维度得分与画像共用一条量纲一致通路的'
        '关键; 多作者分配采用名义分值制则是管理导向下的取舍, 其“挂名”代价由年度上限与'
        '职称评审口径两项制度约束承担, 而非由算法本身消化. 需要说明的是, 本系统度量的是'
        '科研活跃度而不是成果质量, 与同行评议互补而非替代; {i|α} 与 {i|λ} 目前取自经验值, '
        '尚缺少敏感性分析的支撑. 后续将补齐这部分实验, 并与人事、财务等系统打通数据.')
log.append('【文风】结论原来第三次复述“针对…; 将…; 基于…”三点贡献. 改为先给结果, '
           '再给一句真正的判断（衰减该放在哪一层、名义分值制的代价由谁承担）, '
           '最后如实交代两条局限——比复读贡献更像研究者自己写的')

save(tree, SRC, 'work.bak/word/document.xml')
print('已完成：')
for l in log:
    print('  ·', l)
