"""第八步：把 7 处“参考了/借鉴了…的思路[n]”改成有实质内容的表述, 并合并同类项。"""
import xml.etree.ElementTree as ET
from lib import W, register, rewrite, find, text_of, save

SRC = 'work/word/document.xml'
register(SRC)
tree = ET.parse(SRC)
body = tree.getroot().find(W + 'body')
log = []


def sub(needle, pairs, note):
    p = find(body, needle)
    s = text_of(p)
    for a, b in pairs:
        assert a in s, (needle, a[:30])
        s = s.replace(a, b, 1)
    rewrite(p, s)
    log.append(note)


