lib.register(SRC)
tree = ET.parse(SRC)
body = tree.getroot().find(W + 'body')


def fix(anchor, old, new, tag):
    run_replace(find(body, anchor), old, new)
    print('  %-6s %+4d 字  %s' % (tag, len(new) - len(old), anchor[:20]))


