tree = ET.parse(SRC)
body = tree.getroot().find(W + 'body')


def patch(anchor, old, new):
    """run 级替换，保留该段其余 run 的格式。"""
    p = find(body, anchor)
    for t in p.iter(W + 't'):
        if t.text and old in t.text:
            t.text = t.text.replace(old, new)
            return
    raise AssertionError('未命中【%s】于【%s】' % (old[:30], anchor))


def swap(anchor, old, new):
    """整段无格式，可从纯文本重写。"""
    p = find(body, anchor)
    t = text_of(p)
    assert old in t, '未命中【%s】:\n%s' % (old[:40], t[:300])
    rewrite(p, t.replace(old, new))


