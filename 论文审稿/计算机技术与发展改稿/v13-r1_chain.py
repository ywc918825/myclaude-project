# -*- coding: utf-8 -*-
"""R1 专家组第三轮：恢复被抹掉的变量格式，接通计算链路，补两处小修。

【回归修复】前几轮多处改动用 rewrite(p, text_of(p).replace(...)) 回写，而
text_of() 只取纯文本，导致 5 个段落的斜体/上下标被整体抹平——公式里是 Sᵢ、
正文里却成了 Si。本脚本按原稿的格式重建这些段落。

【实质修改】
1. 式(1) 输出 S_i 与式(4) 输入 s_{i,u} 本是同一个量，论文用两套符号且称后者为
   "原始积分"，字面上像分配之前的值。全稿最核心的主张"共用一条量纲一致的计算
   通路"在第一环就断了。此处显式接通。
2. 3.3 节补出 j=1,2,3 的具体权重值（不新增表，避免全篇表号重排）。
3. 3.4 节一处半角句号（数字后，此前扫描规则未覆盖）——该段格式尚存，故用
   run 级替换而非整段重写。
"""
import sys, xml.etree.ElementTree as ET
sys.path.insert(0, '.')
import lib
from lib import W, rewrite, text_of, find, save

SRC = 'unz/word/document.xml'
lib.register(SRC)
tree = ET.parse(SRC)
body = tree.getroot().find(W + 'body')


def patch_runs(p, old, new):
    """在单个 run 内做替换，保留该段其余 run 的格式。"""
    for t in p.iter(W + 't'):
        if t.text and old in t.text:
            t.text = t.text.replace(old, new)
            return True
    return False


def light(anchor, fn):
    """整段无格式可保时，从纯文本重建并插入标记。"""
    p = find(body, anchor)
    t = fn(text_of(p))
    rewrite(p, t)


# ── 1. 式(1) 式中：恢复 S_i / S_total / n 的斜体与下标 ─────────────
rewrite(find(body, '为第 i 作者获得的积分'),
    '式中：{i|S}{sub|i} 为第 {i|i} 作者获得的积分；{i|S}{sub|total} 为成果标准积分；'
    '{i|n} 为作者总数。第 1、2、3 作者的分配系数分别为 1.0、0.8、0.5，'
    '第 4 作者及以后按 0.2 计；通讯作者按第 1 作者计，共同第一作者按并列第 1 作者计。'
    '当成果存在通讯作者（非第 1 作者）或共同第一作者时，'
    '相应作者均按第 1 作者系数 1.0 计，合计上限相应放宽。')

# ── 2. 式(4)(5) 式中：恢复全部变量格式 + 接通式(1) → 式(4) ─────────
rewrite(find(body, '为用户 u 在标签 t 上第 k 个周期'),
    '式中：{i|s̃}{sub|i,u} 为行为 {i|i} 经时间衰减与归一化后的积分；'
    '{i|W}{sup|(k)}{sub|t,u} 为用户 {i|u} 在标签 {i|t} 上第 {i|k} 个周期'
    '（本文指自然年度）的权重，初值 {i|W}{sup|(0)}{sub|t,u} 取 0；'
    '{i|s}{sub|i,u} 为用户 {i|u} 在行为 {i|i} 上经式(1) 分配所得的积分，'
    '即式(1) 中的 {i|S}{sub|i}，两式由此衔接为同一条计算通路；'
    '{i|m} 为标签 {i|t} 下的行为总数；'
    '{i|S}{sub|max,t} 为该行为所属周期全中心在标签 {i|t} 下的最高行为积分，'
    '用于将行为项归一化至 [0, 1]；'
    '{i|w}{sub|i} 为行为 {i|i} 的贡献系数，满足 Σ{i|w}{sub|i} = 1；'
    '{i|τ}{sub|now} 为评价时刻，{i|τ}{sub|i} 为成果完成时间，'
    '故式(4) 按成果相对评价时刻的绝对年龄衰减。'
    '式(4) 作用于归一化之前，刻画成果完成先后的连续差异；'
    '式(5) 作用于周期之间，提供跨周期的指数平滑。'
    '两式共同决定成果的时效权重，其合成效果见 3.3 节参数取值的说明。')

# ── 3. 3.3 参数段：恢复格式 + 补 j=1,2,3 的具体权重 ────────────────
rewrite(find(body, '式(5)中 α 取 0.7'),
    '式(5)中 {i|α} 取 0.7，即最新周期贡献占 70%、历史累积占 30%，'
    '各期权重按 {i|α}(1 − {i|α}){sup|j} 衰减'
    '（{i|j} 为自当前周期往回数的期序，区别于式(5) 的求和下标 {i|i}）；'
    '式(4)中的时间衰减系数取 {i|λ} = 0.14。'
    '两式合成后，{i|j} 个周期前的成果相对当期的权重为 '
    '[(1 − {i|α})e{sup|−λ}]{sup|j} ≈ 0.261{sup|j}'
    '（{i|j} = 1、2、3 时分别约为 0.261、0.068、0.018），'
    '最近 3 个年度周期累计贡献约 98%，与事业单位近三年考核口径相吻合。'
    '该权重序列由 {i|α} 主导（1 − {i|α} = 0.30 远小于 e{sup|−λ} = 0.87），'
    '{i|λ} 的作用是在此基础上按成果完成时间做连续修正——'
    '既区分同一周期内成果的完成先后，避免年末集中申报与年初申报等权，'
    '也使跨周期的衰减不局限于周期粒度的阶跃。'
    '需要明确的是，上述取值使模型度量的是{b|当前科研活跃度}——'
    '对近期成果显著加权，而非对多年积累作等权累计；'
    '若评价目的转向长周期积累，需相应下调 {i|α}，仅调整 {i|λ} 无法改变该特性。')

# ── 4. 标签评估段：恢复 F 的斜体 ───────────────────────────────────
light('为评价标签准确性', lambda t: t.replace('F1 值', '{i|F}1 值'))

# ── 5. 英文摘要：恢复 α、λ 的斜体（并改回希腊字母） ─────────────────
light('Abstract: Research talent evaluation',
      lambda t: (t.replace('(alpha = 0.7)', '({i|α} = 0.7)')
                  .replace('(lambda = 0.14)', '({i|λ} = 0.14)')))

# ── 6. 3.4 节半角句号：该段格式尚存，只动一个 run ──────────────────
p = find(body, 'Cd,min 与 Cd,max 分别为全中心用户')
assert patch_runs(p, '60. ', '60。'), '未找到 “60. ”'

save(tree, SRC, 'ref.xml')
print('R1 done')
