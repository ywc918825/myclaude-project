# -*- coding: utf-8 -*-
"""S2 学术内容层：德尔菲法表述、表4口径说明、结论局限性改写、新增同类工作对比表。"""
import re, sys, copy, xml.etree.ElementTree as ET
sys.path.insert(0, '.')
import lib
from lib import W, rewrite, text_of, find, save

SRC = 'unz/word/document.xml'
lib.register(SRC)
tree = ET.parse(SRC)
body = tree.getroot().find(W + 'body')

# ── 1. “德尔菲法/3 名专家”改为如实表述并交代局限 ────────────────────
p = find(body, '由 3 名科研管理专家按德尔菲法两轮打分确定')
old = text_of(p)
new = old.replace(
    '由 3 名科研管理专家按德尔菲法两轮打分确定, 打分流程沿用省级疾控信息化评价指标的构建方式[3]',
    '由本中心 3 名具有高级职称的科研管理专家经两轮独立打分与组间反馈修正确定, '
    '打分流程参照省级疾控信息化评价指标的构建方式[3]; '
    '受机构规模限制, 参与标定的专家人数偏少, 该矩阵反映的是本中心的评价导向, '
    '跨机构应用时需重新标定')
assert new != old, 'delphi not replaced'
rewrite(p, new)

# ── 2. 表 4 口径说明（申报单量 7.4 倍增幅的可比性） ──────────────────
p = find(body, '申报单量增至上线前的 7.4 倍')
rewrite(p,
    '由表4可见, 系统上线后申报与审核全流程线上化, 申报单量增至上线前的 7.4 倍, '
    '平均审核周期由 7 d 降至 2 d, 科研人员参与度明显提升. 需说明统计口径: '
    '上线前的申报单量取自纸质台账登记数, 上线后取自系统申报记录, '
    '两者并非严格同口径——线下阶段存在漏登记与合并登记, '
    '故该增幅同时反映了参与度提升与登记完整性改善两方面的作用; '
    '而审核周期、超时未办结件数与核算差错率三项在上线前后均按同一业务定义统计, 具有可比性.')

# ── 3. 结论：把“尚缺少支撑”改成规范的局限性陈述 ─────────────────────
p = find(body, '5  结论与展望', 0)
p = find(body, '把时间衰减放在行为积分层')
rewrite(p,
    '系统在南通市疾病预防控制中心运行 3 个月, 平均审核周期由 7 d 降至 2 d, '
    '积分核算差错率由 3.54% 降至 0.08%, 动态能力标签与专家标注的 F1 值为 0.86. '
    '把时间衰减放在行为积分层而不是能力得分层, 是让标签权重、能力维度得分与画像'
    '共用一条量纲一致通路的关键; 多作者分配采用名义分值制则是管理导向下的取舍, '
    '其“挂名”代价由年度上限与职称评审口径两项制度约束承担, 而非由算法本身消化. '
    '本文工作尚存三点局限: 其一, 系统度量的是科研活跃度而非成果质量, '
    '与同行评议互补而非替代; 其二, α 与 λ 依据事业单位近三年考核口径与 5 年聘期设定, '
    '制度依据明确, 但其取值区间对人才排名的影响程度仍有待更大样本的敏感性分析验证; '
    '其三, 标签—能力维度映射矩阵由本中心专家标定, 跨机构推广时需重新标定. '
    '后续将在积累更长周期的积分流水后开展参数敏感性分析与跨机构验证, '
    '并与人事、财务等系统打通数据.')

save(tree, SRC, 'ref.xml')
print('S2 done')
