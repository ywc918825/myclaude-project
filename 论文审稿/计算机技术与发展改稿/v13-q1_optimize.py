"""Q1 按写作团队复议结论优化正文（五项）。

1. 引言末补明确的贡献陈述——本稿被判"像工程报告"，缺的正是这一段
2. 3.3 节 λ 作用描述精确化（它同时作用于周期内与跨周期，原句只说了前者）
3. 3.6 节删除与文献[27]标题不匹配的弱引文（工程做法本不需要引文支撑）
4. 结论四点局限合并为三点，把"活跃度≠质量"与"偏重近期"并为一条并转化表述
5. 表5 改为方法类别对比，不再对具体文献逐项断言（消除 B3 核实风险）
"""
import sys, copy, xml.etree.ElementTree as ET
sys.path.insert(0, '.')
import lib
from lib import W, rewrite, text_of, find, save

SRC = 'unz/word/document.xml'
lib.register(SRC)
tree = ET.parse(SRC)
body = tree.getroot().find(W + 'body')


def sub(anchor, old, new):
    p = find(body, anchor)
    t = text_of(p)
    assert old in t, '未命中【%s】:\n%s' % (old[:50], t[:300])
    rewrite(p, t.replace(old, new))


# ── 1. 引言末：明确三项贡献 ────────────────────────────────────────
sub('现有研究多从指标体系视角',
    '是须先解决的三个具体问题。',
    '是须先解决的三个具体问题。针对这三个问题，本文的主要工作为：'
    '其一，提出基于 Kronecker δ 函数的分段权重积分分配模型，'
    '以名义分值制替代总量守恒制，并给出与三种守恒型方法的系数对比；'
    '其二，将指数时间衰减前置嵌入行为积分归一化环节，'
    '与一阶指数加权移动平均共同构成成果的时效权重，'
    '使标签权重、能力维度得分与人才画像共用一条量纲一致的计算通路；'
    '其三，以有限状态机实现无第三方框架依赖的轻量级审批引擎，'
    '审核环节由配置表驱动，修改配置即可调整而无需重新发布。')

# ── 2. 3.3 节：λ 的作用范围写准 ───────────────────────────────────
sub('式(5)中 α 取 0.7',
    'λ 的作用是在此基础上按成果完成时间做连续修正，'
    '使同一周期内早完成与晚完成的成果不致等权，避免年末集中申报。',
    'λ 的作用是在此基础上按成果完成时间做连续修正——'
    '既区分同一周期内成果的完成先后，避免年末集中申报与年初申报等权，'
    '也使跨周期的衰减不局限于周期粒度的阶跃。')

# ── 3. 3.6 节：删除与文献[27]不匹配的弱引文，后续引文编号前移 ──────
sub('系统引入 Redis 缓存应对高频积分查询',
    '数据库层面借鉴索引列顺序与选择性的一般性优化结论[27]'
    '为核心查询路径建立联合索引',
    '数据库层面按查询模式为核心访问路径建立联合索引')
sub('系统引入 Redis 缓存应对高频积分查询',
    '整合 Spring Security 与 JWT 实现无状态认证[28,29]',
    '整合 Spring Security 与 JWT 实现无状态认证[27,28]')
sub('测试环境为 4 核 CPU',
    '并发梯度参考开源 Web 项目性能测试的实践设置[30]',
    '并发梯度参考开源 Web 项目性能测试的实践设置[29]')

# ── 4. 结论：四点局限合并为三点并转化表述 ──────────────────────────
p = find(body, '本文工作尚存四点局限')
t = text_of(p)
i = t.index('本文工作尚存四点局限')
rewrite(p, t[:i] +
    '本文工作尚存三点局限：其一，受式(4)(5) 合成的年度保持率（约 0.26）所限，'
    '模型刻画的是近三年的科研活跃度而非长期学术积累，亦不评价成果质量，'
    '宜与同行评议互补使用；两参数取值对排名的影响程度仍有待更大样本的'
    '敏感性分析验证。其二，标签—能力维度映射矩阵由本中心专家标定，'
    '跨机构推广时需重新标定。其三，式(4) 采用极值归一化，'
    '对周期内出现的异常高分较为敏感。'
    '后续将在积累更长周期的积分流水后开展参数敏感性分析与跨机构验证，'
    '并与人事、财务等系统打通数据。')

# ── 5. 表5：改为方法类别对比 ───────────────────────────────────────
ROWS = [
    ['对比维度',        '机构层面评价指标体系', '通用用户画像与动态标签', '本文'],
    ['评价对象',        '机构',            '个人（消费/学习行为）',  '个人（科研人员）'],
    ['数据来源',        '统计指标填报',      '行为日志',          '成果申报积分流水'],
    ['多作者成果分配',   '未涉及',           '未涉及',           '分段权重法（式(1)）'],
    ['成果时效处理',    '未涉及',           '指数加权/时间衰减',    '前置嵌入归一化（式(4)(5)）'],
    ['量化与画像同源',   '否',              '部分',             '是'],
    ['审批流程支持',    '未涉及',           '未涉及',           '自研状态机引擎'],
]
tbls = [c for c in body if c.tag == W + 'tbl']
t5 = tbls[-1]
grid = t5.find(W + 'tblGrid')
cols = grid.findall(W + 'gridCol')
for g in cols[4:]:
    grid.remove(g)
for g, wdt in zip(grid.findall(W + 'gridCol'), ('1500', '2100', '2200', '2500')):
    g.set(W + 'w', wdt)
for tr, vals in zip(t5.findall(W + 'tr'), ROWS):
    tcs = tr.findall(W + 'tc')
    for tc in tcs[4:]:
        tr.remove(tc)
    for tc, v in zip(tr.findall(W + 'tc'), vals):
        cps = tc.findall(W + 'p')
        rewrite(cps[0], v)
        for extra in cps[1:]:
            tc.remove(extra)

